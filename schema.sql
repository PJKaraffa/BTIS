-- BTIS v1.0 — Bridgeport Traffic Intelligence System
-- Run in Supabase SQL Editor as project owner.

create extension if not exists pgcrypto;

create type public.app_role as enum ('admin','transportation','school','executive');
create type public.bus_status as enum ('active','maintenance','inactive');
create type public.route_period as enum ('AM','PM','MIDDAY');
create type public.incident_severity as enum ('low','medium','high','critical');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  role public.app_role not null default 'school',
  school_id bigint,
  created_at timestamptz not null default now()
);

create table public.schools (
  id bigint generated by default as identity primary key,
  school_name text not null unique,
  school_code text unique,
  address text,
  latitude double precision not null,
  longitude double precision not null,
  start_time time,
  dismissal_time time,
  student_count integer not null default 0 check (student_count >= 0),
  bus_count integer not null default 0 check (bus_count >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

alter table public.profiles
  add constraint profiles_school_id_fkey foreign key (school_id)
  references public.schools(id) on delete set null;

create table public.buses (
  id bigint generated by default as identity primary key,
  bus_number text not null unique,
  driver_name text,
  vendor text,
  capacity integer check (capacity is null or capacity > 0),
  status public.bus_status not null default 'active',
  current_latitude double precision,
  current_longitude double precision,
  current_speed numeric(6,2),
  delay_minutes integer not null default 0,
  last_gps_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

create table public.routes (
  id bigint generated by default as identity primary key,
  route_number text not null unique,
  school_id bigint not null references public.schools(id) on delete cascade,
  bus_id bigint references public.buses(id) on delete set null,
  period public.route_period not null default 'AM',
  scheduled_start time,
  scheduled_end time,
  estimated_minutes integer check (estimated_minutes is null or estimated_minutes >= 0),
  distance_miles numeric(8,2) check (distance_miles is null or distance_miles >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

create table public.route_stops (
  id bigint generated by default as identity primary key,
  route_id bigint not null references public.routes(id) on delete cascade,
  stop_order integer not null check (stop_order > 0),
  stop_name text,
  address text,
  latitude double precision not null,
  longitude double precision not null,
  scheduled_time time,
  unique(route_id, stop_order)
);

create table public.traffic_incidents (
  id bigint generated by default as identity primary key,
  incident_type text not null,
  severity public.incident_severity not null default 'medium',
  road text,
  latitude double precision not null,
  longitude double precision not null,
  start_time timestamptz not null default now(),
  end_time timestamptz,
  description text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

create table public.gps_positions (
  id bigint generated by default as identity primary key,
  bus_id bigint not null references public.buses(id) on delete cascade,
  latitude double precision not null,
  longitude double precision not null,
  speed numeric(6,2),
  heading numeric(6,2),
  recorded_at timestamptz not null default now()
);

create index gps_positions_bus_time_idx on public.gps_positions(bus_id, recorded_at desc);
create index incidents_active_idx on public.traffic_incidents(active, start_time desc);
create index routes_school_idx on public.routes(school_id);

create or replace function public.current_role()
returns public.app_role
language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() $$;

create or replace function public.is_admin_or_transportation()
returns boolean
language sql stable security definer set search_path = public
as $$ select coalesce(public.current_role() in ('admin','transportation'), false) $$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles(id,email,full_name,role)
  values(new.id,new.email,coalesce(new.raw_user_meta_data->>'full_name',split_part(new.email,'@',1)),'school')
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

