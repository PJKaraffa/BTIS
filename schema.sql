create policy "profiles read own or admin" on public.profiles for select
using (id = auth.uid() or public.current_role() = 'admin');
create policy "profiles admin update" on public.profiles for update
using (public.current_role() = 'admin') with check (public.current_role() = 'admin');

create policy "authenticated read schools" on public.schools for select to authenticated using (true);
create policy "ops manage schools" on public.schools for all to authenticated
using (public.is_admin_or_transportation()) with check (public.is_admin_or_transportation());

create policy "authenticated read buses" on public.buses for select to authenticated using (true);
create policy "ops manage buses" on public.buses for all to authenticated
using (public.is_admin_or_transportation()) with check (public.is_admin_or_transportation());

create policy "authenticated read routes" on public.routes for select to authenticated using (true);
create policy "ops manage routes" on public.routes for all to authenticated
using (public.is_admin_or_transportation()) with check (public.is_admin_or_transportation());

create policy "authenticated read stops" on public.route_stops for select to authenticated using (true);
create policy "ops manage stops" on public.route_stops for all to authenticated
using (public.is_admin_or_transportation()) with check (public.is_admin_or_transportation());

create policy "authenticated read incidents" on public.traffic_incidents for select to authenticated using (true);
create policy "ops manage incidents" on public.traffic_incidents for all to authenticated
using (public.is_admin_or_transportation()) with check (public.is_admin_or_transportation());

